/* speech-data.js — المصدر الوحيد للنصوص العربية المنطوقة (حروف، حركات، مدود، كلمات، أرقام).
   يُحمَّل في المتصفح قبل app.js وgames.js، ويُستعمل أيضًا في Node من tools/gen_lessons.js
   فيتطابق ما يُنطق في التطبيق تمامًا مع ما يُولَّد مسبقًا ويُتحقَّق منه.
   قاعدة التشكيل: كل حرف يحمل حركته، والمد يُكتب بحركة مجانسة قبله (بَا، بُو، بِي)،
   والسكون لا يُنطق منفردًا بل بعد فتحة (أَبْ)، وهمزة الوصل تسقط بعد الواو (وَاثْنَان). */
(function (root) {
  "use strict";
  var FATHA = "\u064E", DAMMA = "\u064F", KASRA = "\u0650", SUKUN = "\u0652";

  /* ---------- الحروف: [الحرف، اسمه المشكول] ---------- */
  var letters = [
    ["أ", "أَلِف"], ["ب", "بَاء"], ["ت", "تَاء"], ["ث", "ثَاء"], ["ج", "جِيم"], ["ح", "حَاء"], ["خ", "خَاء"],
    ["د", "دَال"], ["ذ", "ذَال"], ["ر", "رَاء"], ["ز", "زَاي"], ["س", "سِين"], ["ش", "شِين"], ["ص", "صَاد"],
    ["ض", "ضَاد"], ["ط", "طَاء"], ["ظ", "ظَاء"], ["ع", "عَيْن"], ["غ", "غَيْن"], ["ف", "فَاء"], ["ق", "قَاف"],
    ["ك", "كَاف"], ["ل", "لَام"], ["م", "مِيم"], ["ن", "نُون"], ["ه", "هَاء"], ["و", "وَاو"], ["ي", "يَاء"]
  ];

  /* ---------- مقاطع الحرف ---------- */
  // الهمزة على الألف تُكتب تحت الألف مع الكسرة: إِ (لا أِ)، والمد بالألف مع الهمزة: آ
  function vowelSyl(l, v) { return (l === "أ" && v === KASRA) ? "إ" + KASRA : l + v; }
  // السكون يحتاج حرفًا قبله ينطق به: أَبْ، أَتْ ... ، وللهمزة: أَأْ
  function sukunSyl(l) { return "أ" + FATHA + l + SUKUN; }
  function maddSyl(l, kind) {
    if (kind === "a") return l === "أ" ? "آ" : l + FATHA + "ا";
    if (kind === "u") return l + DAMMA + "و";
    return (l === "أ" ? "إ" : l) + KASRA + "ي";
  }
  function harakat(l) {
    return [
      [vowelSyl(l, FATHA), "فَتْحَة"], [vowelSyl(l, KASRA), "كَسْرَة"],
      [vowelSyl(l, DAMMA), "ضَمَّة"], [sukunSyl(l), "سُكُون"]
    ];
  }
  function madds(l) {
    return [
      [maddSyl(l, "a"), "مَدُّ الأَلِف"], [maddSyl(l, "u"), "مَدُّ الوَاو"], [maddSyl(l, "i"), "مَدُّ اليَاء"]
    ];
  }

  /* نوع النص المنطوق: "short" (حركة/سكون) أو "madd" أو "" (غير مقطع). يطابق Python/Java حرفًا بحرف. */
  var RE_SHORT = /^[\u0621-\u064A][\u064E\u064F\u0650]$/;
  var RE_SUKUN = /^\u0623\u064E[\u0621-\u064A]\u0652$/;
  var RE_MADD = /^([\u0621-\u064A][\u064E\u064F\u0650][\u0627\u0648\u064A]|\u0622)$/;
  function sylKind(t) {
    t = String(t || "");
    if (RE_SHORT.test(t) || RE_SUKUN.test(t)) return "short";
    if (RE_MADD.test(t)) return "madd";
    return "";
  }

  /* ---------- ثلاث كلمات مشكولة لكل حرف (الأولى هي كلمة الصورة في وضع الدروس) ---------- */
  var words = [
    ["أَسَد", "أَرْنَب", "أُذُن"], ["بَقَرَة", "بَيْت", "بَاب"], ["تَمْر", "تِين", "تُوت"], ["ثَعْلَب", "ثَوْب", "ثَلْج"],
    ["جَمَل", "جَزَر", "جَبَل"], ["حِصَان", "حَلِيب", "حُوت"], ["خَرُوف", "خُبْز", "خَيْمَة"], ["دُبّ", "دَجَاجَة", "دَرَّاجَة"],
    ["ذُرَة", "ذِئْب", "ذَهَب"], ["رُمَّان", "رَأْس", "رِيشَة"], ["زَرَافَة", "زَهْرَة", "زَيْت"], ["سَمَكَة", "سَيَّارَة", "سَاعَة"],
    ["شَمْس", "شَجَرَة", "شُبَّاك"], ["صَارُوخ", "صَقْر", "صُورَة"], ["ضِفْدَع", "ضَوْء", "ضِرْس"], ["طَائِر", "طَاوِلَة", "طَبِيب"],
    ["ظَرْف", "ظِلّ", "ظَبْي"], ["عِنَب", "عَيْن", "عُصْفُور"], ["غَيْمَة", "غُرَاب", "غَزَال"], ["فِيل", "فَرَاشَة", "فُول"],
    ["قِطَّة", "قَمَر", "قَلَم"], ["كَلْب", "كِتَاب", "كُرَة"], ["لَيْمُون", "لَبَن", "لِسَان"], ["مَوْز", "مَاء", "مِفْتَاح"],
    ["نَحْلَة", "نُور", "نَجْمَة"], ["هِلَال", "هُدْهُد", "هَاتِف"], ["وَرْدَة", "وَلَد", "وَجْه"], ["يَد", "يَمَامَة", "يَاسَمِين"]
  ];
  var pics = ["🦁", "🐄", "svg:tamr", "🦊", "🐪", "🐎", "🐑", "svg:bear", "🌽", "svg:rumman", "🦒", "🐟", "🌞", "🚀", "🐸", "🐦",
    "\u2709\uFE0F", "🍇", "\u2601\uFE0F", "🐘", "🐈", "🐕", "🍋", "🍌", "🐝", "🌙", "🌹", "✋"];
  var lessonWords = words.map(function (w, i) { return [w[0], pics[i]]; });

  /* ---------- الألوان ---------- */
  var colors = [["أَحْمَر", "#e74c3c"], ["أَزْرَق", "#3498db"], ["أَصْفَر", "#f1c40f"], ["أَخْضَر", "#2ecc71"],
    ["بُرْتُقَالِي", "#f39c12"], ["بَنَفْسَجِي", "#9b59b6"], ["وَرْدِي", "#ff7aa2"], ["بُنِّي", "#8b5a2b"],
    ["أَسْوَد", "#222"], ["أَبْيَض", "#fff"], ["رَمَادِي", "#95a5a6"], ["ذَهَبِي", "#d4ac0d"]];

  /* ---------- الأرقام 1..1000 ---------- */
  var U = ["", "وَاحِد", "اِثْنَان", "ثَلَاثَة", "أَرْبَعَة", "خَمْسَة", "سِتَّة", "سَبْعَة", "ثَمَانِيَة", "تِسْعَة"];
  var T = ["", "عَشَرَة", "عِشْرُون", "ثَلَاثُون", "أَرْبَعُون", "خَمْسُون", "سِتُّون", "سَبْعُون", "ثَمَانُون", "تِسْعُون"];
  var H = ["", "مِائَة", "مِائَتَان", "ثَلَاثُ مِائَة", "أَرْبَعُ مِائَة", "خَمْسُ مِائَة", "سِتُّ مِائَة", "سَبْعُ مِائَة", "ثَمَانِي مِائَة", "تِسْعُ مِائَة"];
  function ones(n) { return U[n]; }
  function tens(n) { return T[n]; }
  // الواو العاطفة: همزة الوصل في «اثنان/اثنا» تسقط (وَاثْنَان) فلا تُنطق همزة بعد الواو
  function waw(w) { return "وَ" + (w.indexOf("اِ") === 0 ? "ا" + w.slice(2) : w); }
  function numberWord(n) {
    n = Math.floor(Number(n));
    if (!(n >= 1)) return String(n);
    if (n < 10) return U[n];
    if (n === 10) return T[1];
    if (n === 11) return "أَحَدَ عَشَر";
    if (n === 12) return "اِثْنَا عَشَر";
    if (n < 20) return U[n - 10] + FATHA + " عَشَر";
    if (n < 100) { var u = n % 10, t = Math.floor(n / 10); return u ? U[u] + " " + waw(T[t]) : T[t]; }
    if (n < 1000) { var h = Math.floor(n / 100), r = n % 100; return r ? H[h] + " " + waw(numberWord(r)) : H[h]; }
    if (n === 1000) return "أَلْف";
    return String(n);
  }

  /* نطق خاص بكلمات يخطئ فيها المحرك عند ختمها بتاء مربوطة */
  var SAY = { "نَحْلَة": "نَحْلَه" };

  /* كلمات يخطئ المحرك في نطقها منفردة؛ تُنطق مع اسم الحرف كما في «الحرف، الكلمة» الذي ينطقها صحيحًا (مقطع جاهز أصلًا) */
  var SAY_SOLO = { "غَيْمَة": "غَيْن، غَيْمَة" };

  var api = {
    letters: letters, colors: colors, words: words, lessonWords: lessonWords, pics: pics,
    harakat: harakat, madds: madds, vowelSyl: vowelSyl, sukunSyl: sukunSyl, maddSyl: maddSyl, sylKind: sylKind,
    ones: ones, tens: tens, numberWord: numberWord, SAY: SAY, SAY_SOLO: SAY_SOLO
  };
  if (typeof module !== "undefined" && module.exports) module.exports = api;
  else root.CatSpeech = api;
})(typeof window !== "undefined" ? window : this);
